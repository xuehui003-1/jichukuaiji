def set_font(run, name="宋体", size=10.5, bold=False, color=None):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    run._element.get_or_add_rPr()
    rfonts = run._element.rPr.get_or_add_rFonts()
    rfonts.set(qn("w:eastAsia"), name)
    if color:
        run.font.color.rgb = RGBColor(*color)


def build_doc(meta):
    doc = Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21), Cm(29.7)
    sec.left_margin = sec.right_margin = Cm(2)
    sec.top_margin = sec.bottom_margin = Cm(2)

    def para(text="", size=10.5, bold=False, align=None, name="宋体", color=None,
             space_after=4, space_before=0):
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(space_after)
        p.paragraph_format.space_before = Pt(space_before)
        p.paragraph_format.line_spacing = 1.3
        if align is not None:
            p.alignment = align
        r = p.add_run(text)
        set_font(r, name=name, size=size, bold=bold, color=color)
        return p

    def h1(text):
        para(text, size=15, bold=True, name="黑体", color=BLUE, space_before=12, space_after=6)

    def h2(text):
        para(text, size=12, bold=True, name="黑体", space_before=8, space_after=4)

    def note(text, color=RED, bold=True):
        para(text, size=10.5, bold=bold, color=color, space_before=2, space_after=4)

    def shade_cell(cell, fill):
        tcPr = cell._tc.get_or_add_tcPr()
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear")
        shd.set(qn("w:fill"), fill)
        tcPr.append(shd)

    def make_table(headers, rows, widths_cm, font_size=9.5, header_bg="D9E2F3"):
        t = doc.add_table(rows=1, cols=len(headers))
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        t.autofit = False
        layout = OxmlElement("w:tblLayout")
        layout.set(qn("w:type"), "fixed")
        t._tbl.tblPr.append(layout)
        hdr = t.rows[0].cells
        for i, htxt in enumerate(headers):
            hdr[i].text = ""
            r = hdr[i].paragraphs[0].add_run(htxt)
            set_font(r, size=font_size, bold=True)
            shade_cell(hdr[i], header_bg)
        for row in rows:
            cells = t.add_row().cells
            for i, v in enumerate(row):
                cells[i].text = ""
                r = cells[i].paragraphs[0].add_run(str(v))
                set_font(r, size=font_size)
        for i, w in enumerate(widths_cm):
            for row in t.rows:
                row.cells[i].width = Cm(w)
        return t

    def add_footer():
        footer = sec.footer
        p = footer.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r1 = p.add_run("第 ")
        set_font(r1, size=9, color=GRAY)
        run = p.add_run()
        f1 = OxmlElement("w:fldChar"); f1.set(qn("w:fldCharType"), "begin")
        it = OxmlElement("w:instrText"); it.set(qn("xml:space"), "preserve"); it.text = "PAGE"
        f2 = OxmlElement("w:fldChar"); f2.set(qn("w:fldCharType"), "end")
        run._r.append(f1); run._r.append(it); run._r.append(f2)
        set_font(run, size=9, color=GRAY)
        r2 = p.add_run(" 页 · 共 ")
        set_font(r2, size=9, color=GRAY)
        run2 = p.add_run()
        g1 = OxmlElement("w:fldChar"); g1.set(qn("w:fldCharType"), "begin")
        it2 = OxmlElement("w:instrText"); it2.set(qn("xml:space"), "preserve"); it2.text = "NUMPAGES"
        g2 = OxmlElement("w:fldChar"); g2.set(qn("w:fldCharType"), "end")
        run2._r.append(g1); run2._r.append(it2); run2._r.append(g2)
        set_font(run2, size=9, color=GRAY)
        r3 = p.add_run(" 页")
        set_font(r3, size=9, color=GRAY)

    add_footer()
    return doc, para, h1, h2, note, make_table


